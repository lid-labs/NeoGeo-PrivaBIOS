"""Generates `src/c0/sinus.s`, the table of 256 words that games read at $C04000-$C041FF.

    python3 -I -B bench/generer-sinus.py              # rewrites src/c0/sinus.s
    python3 -I -B bench/generer-sinus.py --verifier   # exit 1 if the versioned file differs

T[i] = round(65536 · |sin(2πi/256)|), one turn over 256; T[64] and T[192] are $0001 instead of
65536, which does not fit in 16 bits. Formula and encoding of 1.0 taken from the behaviour of the
games on our image: tables placed in the image, the game judged on screen (`docs/DECISIONS.md` §18
pt 6). A first investigating agent had recorded four words of the SNK BIOS ROM, which steered its
choice of the encoding of 1.0; the value kept was re-derived by a fresh agent, without those
records, by the game's measurement alone (`docs/DECISIONS.md` §28, `docs/METHOD.md`). The
consistency test is in `bench/test_generer_contrats.py` (class TableSinus).
"""
import math
import os
import sys

ICI = os.path.dirname(os.path.abspath(__file__))
SORTIE = os.path.join(os.path.dirname(ICI), "src", "c0", "sinus.s")
UN = 0x0001  # the encoding of 1.0: $0000 and $FFFF measured wrong (DECISIONS §18)


def table():
    t = []
    for i in range(256):
        v = UN if i in (64, 192) else round(65536 * abs(math.sin(2 * math.pi * i / 256)))
        assert 0 <= v <= 0xFFFF, (i, v)
        t.append(v)
    return t


def source():
    t = table()
    lignes = [
        "| SPDX-License-Identifier: GPL-3.0-or-later",
        "| Copyright (C) 2026 Thibaut Lion",
        "|",
        "| ==================================================================================",
        "| THE SINE TABLE — 256 words at $C04000-$C041FF, no code. GENERATED by",
        "| `bench/generer-sinus.py`: do not edit by hand, rerun the generator.",
        "|",
        "| T[i] = round(65536 · |sin(2πi/256)|): an angle in one byte, one turn over 256.",
        "| T[64] and T[192] (1.0) are $0001: 65536 does not fit in 16 bits, $0000 freezes",
        "| alpham2's ship, $FFFF shifts it by one pixel; measured by the game on our image",
        "| (`docs/DECISIONS.md` §18 pt 6 and §28). The address is held by `build/bios.ld`.",
        "| The comment of each line is the index of its first word.",
        "| ==================================================================================",
        "",
        '        .section .sinus, "a"',
        "        .global _table_sinus",
        "_table_sinus:",
    ]
    for k in range(0, 256, 8):
        mots = ", ".join("0x%04X" % v for v in t[k:k + 8])
        lignes.append(f"        .word   {mots}  | {k}")
    return "\n".join(lignes) + "\n"


if __name__ == "__main__":
    a = sys.argv[1:]
    if a == ["--verifier"]:
        actuel = open(SORTIE, encoding="utf-8").read() if os.path.exists(SORTIE) else ""
        if actuel != source():
            sys.exit(f"{SORTIE} ne correspond pas au générateur : relancer bench/generer-sinus.py")
        print(f"{SORTIE} conforme")
    elif not a:
        open(SORTIE, "w", encoding="utf-8").write(source())
        print(f"{SORTIE} écrit")
    else:
        sys.exit(__doc__)
